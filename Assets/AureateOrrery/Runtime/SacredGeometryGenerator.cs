using UnityEngine;

namespace AureateOrrery
{
    /// <summary>
    /// 天体儀内部に配置する神聖幾何学ベースの
    /// 六角形観測ラティスを生成する静的クラス。
    ///
    /// 中央円と6方向の円配置、
    /// さらに complexity に応じた六角形状の線構造を組み合わせる。
    /// </summary>
    public static class SacredGeometryGenerator
    {
        /// <summary>
        /// Sacred Geometryをベースとした観測用Meshを生成する。
        ///
        /// complexity:
        /// 外側に追加する幾何学レイヤーの数。
        /// </summary>
        public static Mesh Create(int complexity)
        {
            // ============================================================
            // ジオメトリ生成クラス
            // ============================================================

            var g = new CelestialGeometry();


            // ============================================================
            // 中央の基準円
            // ============================================================

            // 全体構造の中心となる円。
            g.Circle(
                .72f,
                .006f
            );


            // ============================================================
            // 6方向の円配置
            // ============================================================

            // 中心から60度間隔で6個の円を配置する。
            //
            // 2π / 6 = π / 3
            //
            // これにより六角対称性を持つ
            // Flower of Life / Seed of Life を連想させる
            // 基本構造を形成する。
            for (int i = 0; i < 6; i++)
            {
                g.Circle(
                    .72f,
                    .004f,

                    // 中心から半径0.72の位置へ
                    // 60度間隔で円の中心を配置する。
                    CelestialGeometry.Radial(
                        i * Mathf.PI / 3,
                        .72f
                    ),

                    // 円を96分割して滑らかな形状にする。
                    96
                );
            }


            // ============================================================
            // 外側の六角形観測構造
            // ============================================================

            // complexity の値に応じて、
            // 少しずつ半径の異なる幾何学レイヤーを追加する。
            for (int k = 0; k < complexity; k++)
            {
                // 各レイヤーを外側へ少しずつずらす。
                float r =
                    1.48f + k * .055f;


                // 六角形の6方向を基準に線を配置する。
                for (int i = 0; i < 6; i++)
                {
                    // 現在の頂点から、
                    // 120度先にある頂点へ線を接続する。
                    //
                    // (i + 2) * π / 3
                    //
                    // 60度 × 2 = 120度
                    //
                    // 単純な六角形の外周ではなく、
                    // 内部を横断する幾何学的な弦を生成する。
                    g.Segment(
                        CelestialGeometry.Radial(
                            i * Mathf.PI / 3,
                            r
                        ),

                        CelestialGeometry.Radial(
                            (i + 2) * Mathf.PI / 3,
                            r
                        ),

                        .004f
                    );
                }
            }


            // ============================================================
            // Mesh生成
            // ============================================================

            // 構築した円と線を1つのMeshとして返す。
            return g.Build(
                "Hexagonal observation lattice"
            );
        }
    }
}